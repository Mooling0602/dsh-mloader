/**
 * Build the browser half of dsh-mloader.
 *
 * Compiles src/client/core.ts with tsconfig.client.json, strips the ESM export
 * keyword from the single emitted module, and inlines the result into the
 * window.__ModuleLoader__ wrapper the web shell executes on the Plugins page.
 *
 * The output is deterministic: the header carries no timestamp and the script
 * records no environment facts, so two builds of the same source produce the
 * same bytes.
 */

import { spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const tscPath = join(repoRoot, 'node_modules', 'typescript', 'bin', 'tsc')
const configPath = join(repoRoot, 'tsconfig.client.json')
const compiledPath = join(repoRoot, '.build', 'client', 'core.js')
const outputPath = join(repoRoot, 'client.js')

const HEADER = [
  '// Generated by scripts/build-client.mjs. Do not edit by hand.',
  '// Source: src/client/core.ts',
  '',
].join('\n')

const WRAPPER_OPEN = [
  'window.__ModuleLoader__.load({',
  '  id: "dsh-mloader",',
  '  factory: (require) => {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
  '    var react = require("react");',
  '    var primitives = require("@deepseek-ai/dsh-client-ui-primitives");',
].join('\n') + '\n'

const WRAPPER_CLOSE = [
  '    var core = createClientCore({ react: react, primitives: primitives });',
  '    exports.inject = ["slots", "locale"];',
  '    exports.apply = core.apply;',
  '    return module.exports;',
  '  }',
  '});',
  '',
].join('\n')

const EXPORT_MARKER = 'export function createClientCore'

/** Print a build failure in the shape the operator can act on, then exit. */
function fail(message) {
  console.error(`client build: ${message}`)
  process.exit(1)
}

if (!existsSync(tscPath)) fail(`TypeScript compiler not found at ${tscPath}; run pnpm install first`)

const compile = spawnSync(process.execPath, [tscPath, '-p', configPath], { cwd: repoRoot, encoding: 'utf8' })
if (compile.status !== 0) {
  if (compile.stdout !== '') process.stderr.write(compile.stdout)
  if (compile.stderr !== '') process.stderr.write(compile.stderr)
  fail('TypeScript compilation failed (tsc -p tsconfig.client.json)')
}

const compiled = await readFile(compiledPath, 'utf8')
const markerIndex = compiled.indexOf(EXPORT_MARKER)
if (markerIndex === -1) fail(`compiled module does not export createClientCore (${compiledPath})`)

const coreSource = `${compiled.slice(0, markerIndex)}function createClientCore${compiled.slice(markerIndex + EXPORT_MARKER.length)}`.replace(/\s+$/, '')
const output = `${HEADER}${WRAPPER_OPEN}${coreSource}\n${WRAPPER_CLOSE}`

await writeFile(outputPath, output, 'utf8')
console.log(`client build: wrote client.js (${Buffer.byteLength(output, 'utf8')} bytes)`)
